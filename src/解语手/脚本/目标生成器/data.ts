/** 引荐的三种场面：决定谁在店里 */
export type ReferralScene = '朋友单独来' | '她在外间等' | '她进房做示范';

export const REFERRAL_SCENES: ReferralScene[] = ['朋友单独来', '她在外间等', '她进房做示范'];

/** 掷签抽出来的客人（自己预约） */
export interface DrawnGuest {
  姓名: string;
  年龄: number;
  职业: string;
  身份: string;
  婚配: Marital;
  心事: Worry;
  由头: string;
  形貌: string;
  性癖: string;
  敏感点: string[];
  性经历: string;
  partner: string;
  pool: Pool;
}

/** 界面与写入变量通用的客人形态：引荐路径会补上来路三件套 */
export interface Guest extends DrawnGuest {
  来路: '自己预约' | '熟人引荐';
  /** 引荐人姓名，自己预约时为空 */
  引荐人: string;
  /** 引荐人转述的那句话，只用于展示 */
  引荐人的话: string;
  知情: boolean;
}

/** 按姓名合成一位客人：姓 + 名 */
export function pickName(taken: Set<string>): string {
  for (let attempt = 0; attempt < 40; attempt++) {
    const name = `${_.sample(SURNAMES)!}${_.sample(GIVEN)!}`;
    if (!taken.has(name)) {
      return name;
    }
  }
  // 极端情况下退化成一个仍可读的组合
  return `${_.sample(SURNAMES)!}${_.sample(GIVEN)!}`;
}

export interface DrawOptions {
  pools: Pool[];
  ageRange: [number, number] | null;
  /** 已被占用的姓名（名册里的 + 当前客人），避免重名 */
  taken: Set<string>;
}

/**
 * 掷一支签：先筛原型，再从原型自带的子池里取各项，保证组合现实合理。
 * 于是「女高管 × 什么都不懂」「研究生 × 守寡十年」这类组合在结构上出不来。
 */
export function drawGuest(options: DrawOptions): DrawnGuest | null {
  const candidates = ARCHETYPES.filter(archetype => {
    if (!options.pools.includes(archetype.pool)) {
      return false;
    }
    if (!options.ageRange) {
      return true;
    }
    return archetype.age[1] >= options.ageRange[0] && archetype.age[0] <= options.ageRange[1];
  });

  if (!candidates.length) {
    return null;
  }

  const archetype = _.sample(candidates)!;
  const lower = Math.max(archetype.age[0], options.ageRange?.[0] ?? archetype.age[0]);
  const upper = Math.min(archetype.age[1], options.ageRange?.[1] ?? archetype.age[1]);
  const age = _.random(lower, Math.max(lower, upper));

  // 形貌：身形（原型池）＋ 职业痕，都只取粗标签；胸腰肤色、疤与痣一概不预写
  const shape = [archetype.shape[0], _.sample(JOB_MARK[archetype.pool])!];

  // 性癖：先取身份匹配的 1~2 条，约四成概率再从本职业池补一条
  const kinks = _.uniq([
    ..._.sampleSize(archetype.kink, _.random(1, 2)),
    ...(_.random(0, 99) < 45 ? _.sampleSize(K_EXTRA[archetype.pool], 1) : []),
  ]).slice(0, 3);

  // 敏感点：去重后取 2~3 处，避免同组堆叠
  const sensitive = _.sampleSize(_.uniq(archetype.sensitive), _.random(2, 3));

  return {
    姓名: pickName(options.taken),
    年龄: age,
    职业: archetype.job,
    身份: archetype.identity,
    婚配: _.sample(archetype.marital)!,
    心事: _.sample(archetype.worry)!,
    由头: _.sample(archetype.reason)!,
    形貌: shape.join('｜'),
    性癖: kinks.join('｜'),
    敏感点: sensitive,
    性经历: _.sample(archetype.sexualHistory)!,
    partner: archetype.partner,
    pool: archetype.pool,
  };
}

/**
 * 熟人引荐：由名册里某位熟客介绍一位朋友。
 *
 * 关键规则：**知情状态跟着引荐人走**——知情的熟客只带知情的朋友，
 * 不知情的只带不知情的。于是"关系网铺到哪一层"是玩家自己经营出来的。
 */
export function drawReferredGuest(options: {
  pools: Pool[];
  ageRange: [number, number] | null;
  taken: Set<string>;
  referrer: { 姓名: string; pool?: Pool; 知情?: boolean };
  /** 引荐人的身份，用来让她介绍"同事""表妹"这类关系 */
  relation?: string;
}): Guest | null {
  // 引荐来的朋友多半与引荐人同类人，所以优先在同职业池里抽；抽不到再放宽
  const samePool = drawGuest({ ...options, pools: options.referrer.pool ? [options.referrer.pool] : options.pools });
  const drawn = samePool ?? drawGuest(options);
  if (!drawn) {
    return null;
  }

  const relation = options.relation ?? _.sample(['我同事', '我朋友', '我表妹', '我一个老同学', '我邻居'])!;

  return {
    ...drawn,
    来路: '熟人引荐',
    引荐人: options.referrer.姓名,
    引荐人的话: `${options.referrer.姓名}跟我提过你，说你这儿手艺好，让我来试试`,
    知情: Boolean(options.referrer.知情),
    // 引荐来的朋友会顺着介绍人给的印象进门，把这一层写进身份里
    身份: `${drawn.身份}；${options.referrer.姓名}的${relation.replace(/^我/, '')}`,
  };
}

/** 把一位掷签客人补成完整形态（自己预约） */
export function asSelfBooked(drawn: DrawnGuest): Guest {
  return {
    ...drawn,
    来路: '自己预约',
    引荐人: '',
    引荐人的话: '',
    知情: false,
  };
}