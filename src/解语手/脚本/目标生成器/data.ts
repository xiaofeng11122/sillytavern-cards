/** 心事：本卡的核心。每类原型自带倾向，AI 按层次往外倒 */
export type Worry = '都市孤独' | '婚姻与冷落' | '职场压力' | '身体与容貌焦虑' | '旧伤与失落' | '家庭与世俗压力';

