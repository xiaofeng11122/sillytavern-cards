/**
 * 目标生成器的签谱。
 *
 * 关键设计：**不做字段独立乱掷**。每个「职业原型」(Archetype) 自带与之相配的年龄区间、
 * 婚配状况、心事倾向、性格/形貌/性癖/敏感点子池，姓名再从姓氏池合成。
 * 于是「女高管 × 什么都不懂」「研究生 × 守寡十年」这类不自洽的组合在结构上不可能出现。
 *
 * 字段取词（**种子式**，与窃玉偷香一致）：
 *   - 性格：「外·<外在>｜内·<她缺的那块>」，两截都只是短标签，是「往哪儿演」的方向
 *   - 形貌：两个粗标签（身形 + 职业留下的痕），细节一律留给演绎当场长出来
 *   - 敏感点：唯一必须精确的字段，只写性事中确有作用的部位
 *   - 性癖：2~3 个真实偏好的短标签，不展开成句
 *   - 心事：本卡特有。每类原型自带倾向，供 AI 分层次往外倒
 *   - 来路：自己预约 / 熟人引荐；引荐时知情状态跟着引荐人走
 *
 * 变量只写入信息卡字段（姓名/年龄/职业/身份/婚配/形貌/性癖/敏感点/性经历/来路）；
 * 「由头」「苦主」仅用于展示与写话，不进 MVU。
 */

