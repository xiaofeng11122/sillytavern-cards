/**
 * 目标生成器的签谱。
 *
 * 关键设计：**不做字段独立乱掷**。每个「身份原型」(Archetype) 自带与之相配的年龄区间、
 * 性经历、性格/形貌/性癖/敏感点子池，姓名再从有朝代语感的姓氏与闺名池合成。
 * 于是「青楼花魁 × 未经人事」「十八岁 × 守寡十年」这类不自洽的组合在结构上不可能出现。
 *
 * 字段取词（**种子式**，用户反馈后改版，见 创作规划.yaml「字段取词」）：
 *   - 性格：「外·<外在>｜内·<内在的缺口>」，两截都只是短标签——外在是给外人看的壳，
 *     内在是她缺的那块。它是「往哪儿演」的方向，不是她的完整人格。
 *   - 形貌：两三个粗标签（身形 + 出身留下的痕），细节（胸腰、肤色、疤、痣）一律不预写，
 *     留给演绎时当场长出来，并与剧情呼应。
 *   - 敏感点：只写性事中确有作用的部位（这是需要精确的字段，必须预写）。
 *   - 性癖：2~3 个真实偏好的短标签，不展开成句；不写「嘴上推拒身体诚实」这类情态
 *     （那属寝取情态，由性经历驱动）。
 *
 * 旧版（已废弃）把这几项预写成整句描写再由酒馆抽取，玩家反馈「太格式化」，
 * 且预制描写与当时的剧情场景常常对不上；故一律降级为标签。
 *
 * 变量只写入信息卡字段（姓名/年龄/身份/性格/形貌/性癖/敏感点/性经历）；
 * 「苦主」仅用于展示一句，交由 AI 按条目演绎，不写进 MVU。
 */

