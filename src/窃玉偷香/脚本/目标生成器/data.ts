/**
 * 按姓名合成一位目标的姓名。
 * 妃嫔用「姓+位号」，其余用「姓+闺名」。
 */
export function pickName(archetype: Archetype, taken: Set<string>): string {
  const surnames = SURNAMES[archetype.名池];
  for (let attempt = 0; attempt < 40; attempt++) {
    const surname = _.sample(surnames)!;
    const given =
      archetype.名池 === 'title' ? _.sample(TITLES)! : _.sample(GIVEN[archetype.名池])!;
    const name = `${surname}${given}`;
    if (!taken.has(name)) {
      return name;
    }
  }
  // 极端情况下退化为「姓 + 位号/闺名 + 娘」，仍可读
  return `${_.sample(surnames)!}${_.sample(GIVEN.commoner)!}`;
}

export interface DrawnTarget {
  姓名: string;
  年龄: number;
  身份: string;
  性格: string;
  身材: string;
  性癖: string;
  敏感点: string;
  性经历: string;
  圈层: Pool;
  /** 仅展示：交给 AI 演绎的苦主一句 */
  苦主: string;
}

export interface DrawOptions {
  pools: Pool[];
  ageRange: [number, number] | null;
  /** 已被占用的姓名（名册里的 + 固定角色），避免重名 */
  taken: Set<string>;
}

/** 掷一支签：先筛原型，再从原型自带的子池里取各项，保证组合现实合理 */
export function drawTarget(options: DrawOptions): DrawnTarget | null {
  const candidates = ARCHETYPES.filter(archetype => {
    if (!options.pools.includes(archetype.圈层)) {
      return false;
    }
    if (!options.ageRange) {
      return true;
    }
    return archetype.年龄[1] >= options.ageRange[0] && archetype.年龄[0] <= options.ageRange[1];
  });

  if (!candidates.length) {
    return null;
  }

  const archetype = _.sample(candidates)!;
  const lower = Math.max(archetype.年龄[0], options.ageRange?.[0] ?? archetype.年龄[0]);
  const upper = Math.min(archetype.年龄[1], options.ageRange?.[1] ?? archetype.年龄[1]);
  const age = _.random(lower, Math.max(lower, upper));
  const sensitivePoints = _.sampleSize(archetype.敏感点, _.random(2, 3));

  return {
    姓名: pickName(archetype, options.taken),
    年龄: age,
    身份: archetype.身份,
    性格: _.sample(archetype.性格)!,
    身材: _.sample(archetype.身材)!,
    性癖: _.sample(archetype.性癖)!,
    敏感点: sensitivePoints.join('、'),
    性经历: _.sample(archetype.性经历)!,
    圈层: archetype.圈层,
    苦主: archetype.苦主,
  };
}
