export interface DrawOptions {
  pools: Pool[];
  ageRange: [number, number] | null;
  /** 已被占用的姓名（名册里的 + 固定角色），避免重名 */
  taken: Set<string>;
}

/** 掷一支签：先筛原型，再从原型自带的子池里取各项，保证组合现实合理 */
export function drawTarget(options: DrawOptions): DrawnTarget | null {
  const candidates = ARCHETYPES.filter(archetype => {
    if (!options.pools.includes(archetype.圈层)) {
      return false;
    }
    if (!options.ageRange) {
      return true;
    }
    return archetype.年龄[1] >= options.ageRange[0] && archetype.年龄[0] <= options.ageRange[1];
  });

  if (!candidates.length) {
    return null;
  }

  const archetype = _.sample(candidates)!;
  const lower = Math.max(archetype.年龄[0], options.ageRange?.[0] ?? archetype.年龄[0]);
  const upper = Math.min(archetype.年龄[1], options.ageRange?.[1] ?? archetype.年龄[1]);
  const age = _.random(lower, Math.max(lower, upper));
  // 去重后取 2~3 处，避免「乳尖、乳晕」这类同组堆叠
  const sensitivePoints = _.sampleSize(_.uniq(archetype.敏感点), _.random(2, 3));

  return {
    姓名: pickName(archetype, options.taken),
    年龄: age,
    身份: archetype.身份,
    性格: _.sample(archetype.性格)!,
    身材: _.sample(archetype.身材)!,
    性癖: _.sampleSize(archetype.性癖, _.random(1, 2)).join('；'),
    敏感点: sensitivePoints.join('、'),
    性经历: _.sample(archetype.性经历)!,
    圈层: archetype.圈层,
    苦主: archetype.苦主,
    情报来源: _.sample(SOURCE[archetype.圈层])!,
    混入身份: _.sample(COVER[archetype.圈层])!,
    踩点: _.sample(RECON[archetype.圈层])!,
    住处: _.sample(WARD[archetype.圈层])!,
    婚配: MARITAL[archetype.身份] ?? '',
  };
}
