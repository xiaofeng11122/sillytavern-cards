/**
 * 按姓名合成一位目标的姓名。
 * 妃嫔用「姓+位号」，其余用「姓+闺名」。
 */
export function pickName(archetype: Archetype, taken: Set<string>): string {
  const surnames = SURNAMES[archetype.名池];
  for (let attempt = 0; attempt < 40; attempt++) {
    const surname = _.sample(surnames)!;
    const given = archetype.名池 === 'title' ? _.sample(TITLES)! : _.sample(GIVEN[archetype.名池])!;
    const name = `${surname}${given}`;
    if (!taken.has(name)) {
      return name;
    }
  }
  // 极端情况下退化成一个仍可读的组合
  return `${_.sample(surnames)!}${_.sample(GIVEN.commoner)!}`;
}

